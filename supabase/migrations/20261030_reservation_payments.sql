-- LAP GEAR · Reservation payments ledger
-- 2026-10-30

create table if not exists public.reservation_payments (
  id bigint generated by default as identity primary key,
  reservation_id uuid not null references public.reservations(id) on delete cascade,
  amount numeric(10,2) not null check (amount <> 0),
  kind text not null default 'payment'
    check (kind in ('payment','deposit','refund','adjustment')),
  method text not null default 'other'
    check (method in ('cash','card','bank_transfer','paypal','other')),
  paid_at timestamptz not null default now(),
  notes text,
  created_at timestamptz not null default now()
);

create index if not exists idx_reservation_payments_reservation
  on public.reservation_payments(reservation_id);

create index if not exists idx_reservation_payments_paid_at
  on public.reservation_payments(paid_at);

alter table public.reservation_payments enable row level security;
revoke all on table public.reservation_payments from anon, authenticated;
