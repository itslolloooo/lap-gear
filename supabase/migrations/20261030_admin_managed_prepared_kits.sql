create table if not exists public.kits (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  eyebrow text not null default '',
  description text not null default '',
  ideal_for text[] not null default '{}',
  active boolean not null default true,
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.kit_items (
  id bigint generated by default as identity primary key,
  kit_id bigint not null references public.kits(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete restrict,
  quantity integer not null default 1 check (quantity > 0 and quantity <= 99),
  position integer not null default 0,
  unique (kit_id, product_id)
);

create index if not exists idx_kit_items_kit_id on public.kit_items(kit_id);
create index if not exists idx_kit_items_product_id on public.kit_items(product_id);
create index if not exists idx_kits_active_position on public.kits(active, position);

alter table public.kits enable row level security;
alter table public.kit_items enable row level security;

revoke all on table public.kits from anon, authenticated;
revoke all on table public.kit_items from anon, authenticated;

